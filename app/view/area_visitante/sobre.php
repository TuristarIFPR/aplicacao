              Por trás dessa iniciativa está uma equipe comprometida em transformar a maneira como viajamos e aprendemos. O projeto foi idealizado por Lucas Gabriel e Stephany Cardoso, criadores do Turistar, que uniram suas habilidades e visões para construir uma plataforma capaz de preencher essa lacuna informativa.
              Juntos, buscamos oferecer ao público não apenas um site, mas uma ferramenta capaz de ensinar, inspirar e conectar pessoas ao valor histórico e cultural dos destinos brasileiros. O Turistar foi desenvolvido com dedicação para que cada usuário possa explorar o Brasil com mais consciência, conhecimento e encantamento, descobrindo a verdadeira riqueza que vai muito além do turismo tradicional.</p>
